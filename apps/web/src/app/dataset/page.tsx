import Link from 'next/link';
import type { ReactNode } from 'react';

import type { ProvenanceKind } from '@civora/domain';
import { DEMO_SEED } from '@civora/simulator';
import type { SourceStatus } from '@civora/simulator';

import { CountList, DataTable, Notice, Panel, StatCard, formatCount } from '@/components/ui';
import { RETRIEVAL_DATE, SOURCE_REGISTRY, getDemoDataset } from '@/lib/dataset';

/**
 * The dataset inspector.
 *
 * This page exists to answer one question honestly: what is this platform
 * actually running on? Every other screen will show derived intelligence — a
 * forecast, a risk score, a proposed transfer — and each of those is only as
 * trustworthy as the data underneath it. A reviewer should be able to come
 * here, before believing any of it, and see how much of the dataset is real,
 * how much is assumed, how much is generated, and which of the sources the
 * project set out to use turned out to be unobtainable.
 *
 * It reads the generator rather than the store, and that is deliberate: the
 * figures here are the generator's own output counted, so the page cannot
 * agree with a configuration while the data says something else.
 *
 * Rendering is static. The dataset is deterministic, so baking it at build time
 * costs one generation and saves one per request.
 */

/** How each provenance kind is described to a reader. */
const PROVENANCE_LABELS: Readonly<Record<ProvenanceKind, string>> = {
  source: 'Read from a publication',
  derived: 'Computed from other values',
  simulated: 'Generated by the simulator',
  assumption: 'A stated assumption',
};

const PROVENANCE_TONES: Readonly<Record<ProvenanceKind, string>> = {
  source: 'border-signal-ok/40 bg-signal-ok/10 text-signal-ok',
  derived: 'border-accent/40 bg-accent/10 text-accent',
  simulated: 'border-signal-watch/40 bg-signal-watch/10 text-signal-watch',
  assumption: 'border-violet-500/40 bg-violet-500/10 text-violet-200',
};

const SOURCE_STATUS_TONES: Readonly<Record<SourceStatus, string>> = {
  retrieved: 'border-signal-ok/40 bg-signal-ok/10 text-signal-ok',
  partial: 'border-signal-watch/40 bg-signal-watch/10 text-signal-watch',
  failed: 'border-signal-critical/40 bg-signal-critical/10 text-signal-critical',
};

const SOURCE_STATUS_LABELS: Readonly<Record<SourceStatus, string>> = {
  retrieved: 'retrieved',
  partial: 'partly retrieved',
  failed: 'not retrieved',
};

function Badge({
  children,
  className,
}: {
  readonly children: ReactNode;
  readonly className: string;
}) {
  return (
    <span
      className={`inline-block rounded-full border px-2 py-0.5 font-mono text-xs whitespace-nowrap ${className}`}
    >
      {children}
    </span>
  );
}

export default function DatasetPage() {
  const demo = getDemoDataset();
  const { summary } = demo;
  const scenario = demo.simulation.scenario;

  return (
    <div className="flex flex-col gap-12">
      <header className="flex flex-col gap-3">
        <p className="font-mono text-eyebrow text-accent uppercase">Dataset inspector</p>
        <h1 className="text-display text-balance">What this platform is running on</h1>
        <p className="max-w-measure text-lg text-fg-muted">
          The demonstration dataset, counted from the generator that produces it. Every figure below
          is reproducible from one published seed, and every record says in its own fields where it
          came from.
        </p>
      </header>

      <Notice id="simulated" tone="warning" title="Everything the platform observes is simulated">
        <p>
          Nothing on this page came from a health facility. Every stock ledger entry, syndromic
          signal, bed report, attendance record and footfall observation in this dataset was
          generated by the simulator in this repository, and every one of them carries{' '}
          <code className="font-mono text-signal-watch">synthetic: true</code> with a simulated
          provenance. A test enforces that, so a record cannot be emitted without it.
        </p>
        <p className="text-signal-watch/70">
          The anchoring is what is real: district populations are Census 2011 values and the item
          catalogue is the National List of Essential Medicines 2022, cited in the table below.
          Where a value had to be assumed it is marked as assumed, and where a source could not be
          retrieved it is recorded as a failure rather than replaced with something plausible.
        </p>
      </Notice>

      <Panel
        id="identity"
        title="The dataset"
        description={
          <>
            One seed, one scenario and one window, all published. A reviewer with this repository
            can regenerate the exact dataset these figures describe.
          </>
        }
      >
        <div className="grid gap-3 sm:grid-cols-3 lg:grid-cols-6">
          <StatCard label="Seed" value={DEMO_SEED} />
          <StatCard label="Scenario" value={scenario.id} hint={scenario.label} />
          <StatCard
            label="Window"
            value={`${summary.window.from} → ${summary.window.to}`}
            hint={`${String(summary.window.days)} days`}
          />
          <StatCard
            label="Facilities"
            value={formatCount(summary.totals.facilities)}
            hint={`${String(summary.totals.simulatedFacilities)} with a history`}
          />
          <StatCard
            label="Items"
            value={formatCount(summary.totals.items)}
            hint={`${formatCount(summary.totals.itemHistories)} item histories`}
          />
          <StatCard
            label="Generated in"
            value={`${String(demo.generatedInMs)} ms`}
            hint={`anchors retrieved ${RETRIEVAL_DATE}`}
          />
        </div>
        <p className="max-w-measure text-sm text-fg-muted">
          <span className="text-fg-muted">Coverage and depth are separate decisions.</span> The
          network states the whole country at the profile&rsquo;s width —{' '}
          {formatCount(summary.totals.states)} states, {formatCount(summary.totals.districts)}{' '}
          districts, {formatCount(summary.totals.blocks)} blocks — while a generated{' '}
          <em>history</em> exists for {formatCount(summary.totals.simulatedFacilities)} facilities,
          spread across every state. A figure that could be read either way says which one it is.
        </p>
        <p className="max-w-measure text-sm text-fg-muted">
          The run is a scripted perturbation with a named expectation:{' '}
          <span className="text-fg-muted">{scenario.expectation}</span>
          {scenario.negativeControl
            ? ' This is a negative control, so the correct result is silence.'
            : ''}
        </p>
      </Panel>

      <Panel
        id="provenance"
        title="Where each layer comes from"
        description={
          <>
            Counted from the records themselves rather than declared, so this table cannot state an
            origin the data does not carry. It is the whole honest answer to &ldquo;is any of this
            real?&rdquo; in one place.
          </>
        }
      >
        <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
          {summary.provenance.map((layer) => (
            <StatCard
              key={layer.kind}
              label={layer.kind}
              value={formatCount(layer.records)}
              hint={PROVENANCE_LABELS[layer.kind]}
            />
          ))}
        </div>
        <DataTable
          caption="Records by provenance kind, with the layers that carry it and the references named"
          columns={[
            { header: 'Kind' },
            { header: 'Records', numeric: true },
            { header: 'What carries it' },
            { header: 'Named as' },
          ]}
          rows={summary.provenance.map((layer) => [
            <Badge key="kind" className={PROVENANCE_TONES[layer.kind]}>
              {layer.kind}
            </Badge>,
            formatCount(layer.records),
            <ul key="layers" className="flex flex-col gap-0.5">
              {layer.layers.map((each) => (
                <li key={each.label} className="text-fg-muted">
                  {each.label}{' '}
                  <span className="font-mono text-fg-subtle">{formatCount(each.count)}</span>
                </li>
              ))}
            </ul>,
            <ul key="refs" className="flex flex-col gap-0.5 font-mono text-xs text-fg-muted">
              {layer.references.map((reference) => (
                <li key={reference}>{reference}</li>
              ))}
            </ul>,
          ])}
        />
        <p className="max-w-measure text-sm text-fg-subtle">
          Purchase orders are absent from this table because they are the generator&rsquo;s own
          bookkeeping rather than a record the platform stores. Nothing reads one as evidence yet.
        </p>
      </Panel>

      <Panel
        id="sources"
        title="What the dataset is anchored on"
        description={
          <>
            Every external value the dataset rests on is registered here with the date it was
            fetched. A source that could not be obtained is recorded as a failure; the value
            standing in for it is marked as an assumption in the records that use it, so the dataset
            never silently substitutes a plausible number for a published one.
          </>
        }
      >
        <DataTable
          caption="Registered sources with their publisher, licence, retrieval date and status"
          columns={[
            { header: 'Source' },
            { header: 'Status' },
            { header: 'Licence' },
            { header: 'Retrieved' },
          ]}
          rows={SOURCE_REGISTRY.map((source) => [
            <div key="source" className="flex flex-col gap-1">
              <span className="text-fg">{source.title}</span>
              <span className="text-xs text-fg-subtle">{source.publisher}</span>
              <details className="max-w-xl">
                <summary className="cursor-pointer text-xs text-accent">what was obtained</summary>
                <p className="mt-1 text-xs text-fg-muted">{source.note}</p>
              </details>
            </div>,
            <Badge key="status" className={SOURCE_STATUS_TONES[source.status]}>
              {SOURCE_STATUS_LABELS[source.status]}
            </Badge>,
            <span key="licence" className="text-xs text-fg-muted">
              {source.licence}
            </span>,
            <span key="date" className="font-mono text-xs text-fg-muted">
              {source.retrievedOn}
            </span>,
          ])}
        />
      </Panel>

      <Panel
        id="by-state"
        title="By state"
        description={
          <>
            The administrative spine, counted per state. &ldquo;Anchored&rdquo; means the state
            population was read from the census listing rather than allocated across the residual
            national total.
          </>
        }
      >
        <DataTable
          caption="Districts, blocks, facilities and simulated facilities per state"
          columns={[
            { header: 'State' },
            { header: 'Districts', numeric: true },
            { header: 'Blocks', numeric: true },
            { header: 'Facilities', numeric: true },
            { header: 'With history', numeric: true },
            { header: 'Population' },
          ]}
          rows={summary.byState.map((state) => [
            state.name,
            formatCount(state.districts),
            formatCount(state.blocks),
            formatCount(state.facilities),
            formatCount(state.simulatedFacilities),
            <span key="population" className="flex items-center gap-2">
              <span className="font-mono">{formatCount(state.population)}</span>
              <Badge
                className={
                  state.populationAnchored
                    ? SOURCE_STATUS_TONES.retrieved
                    : SOURCE_STATUS_TONES.partial
                }
              >
                {state.populationAnchored ? 'census' : 'allocated'}
              </Badge>
            </span>,
          ])}
        />
      </Panel>

      <Panel
        id="by-tier"
        title="By facility tier"
        description={
          <>
            Facilities are sited against the published care norms for their tier, and the items a
            tier is expected to hold follow the level-of-care markers on the essential medicines
            list.
          </>
        }
      >
        <DataTable
          caption="Facilities, simulated facilities, cold-chain capability and catalogue size per tier"
          columns={[
            { header: 'Tier' },
            { header: 'Facilities', numeric: true },
            { header: 'With history', numeric: true },
            { header: 'Cold-chain capable', numeric: true },
            { header: 'Items held', numeric: true },
            { header: 'Population norm' },
            { header: 'Bed norm' },
          ]}
          rows={summary.byTier.map((tier) => [
            <span key="tier" className="flex flex-col">
              <span className="text-fg">{tier.tier}</span>
              <span className="text-xs text-fg-subtle">{tier.label}</span>
            </span>,
            formatCount(tier.facilities),
            formatCount(tier.simulatedFacilities),
            formatCount(tier.coldChainCapable),
            formatCount(tier.itemsHeld),
            `${formatCount(tier.normPopulation[0])}–${formatCount(tier.normPopulation[1])}`,
            `${formatCount(tier.normBeds[0])}–${formatCount(tier.normBeds[1])}`,
          ])}
        />
        <p className="max-w-measure text-sm text-fg-subtle">
          A tier with no facilities is still listed: the profile states which tiers it covers, and
          the tier table is where that is visible rather than implied.
        </p>
      </Panel>

      <Panel
        id="catalogue"
        title="The item catalogue"
        description={
          <>
            {formatCount(summary.catalogue.total)} generic medicines and vaccines, drawn from the
            national essential medicines list. Storage class is what constrains a redistribution: a
            vaccine cannot move to a facility with no working cold chain, however short that
            facility is.
          </>
        }
      >
        <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
          <StatCard label="Items" value={formatCount(summary.catalogue.total)} />
          <StatCard
            label="Cold chain"
            value={formatCount(summary.catalogue.coldChainItems)}
            hint="must travel and store cold"
          />
          <StatCard
            label="Surge-sensitive"
            value={formatCount(summary.catalogue.surgeSensitiveItems)}
            hint="consumption rises with a case surge"
          />
          <StatCard
            label="Categories"
            value={formatCount(summary.catalogue.byCategory.length)}
            hint="clinical groupings"
          />
        </div>
        <div className="grid gap-3 lg:grid-cols-3">
          <CountList
            id="catalogue-category"
            title="By therapeutic category"
            counts={summary.catalogue.byCategory}
          />
          <CountList
            id="catalogue-storage"
            title="By storage class"
            counts={summary.catalogue.byStorage}
          />
          <CountList
            id="catalogue-care"
            title="By level of care"
            counts={summary.catalogue.byCareLevel}
            footnote="An item can be listed at more than one level, so these do not sum to the catalogue size."
          />
        </div>
      </Panel>

      <Panel
        id="by-district"
        title="By district"
        description={
          <>
            Every district the profile models. This is the level at which redistribution authority
            realistically sits, so it is the level the later phases report at.
          </>
        }
      >
        <DataTable
          caption="Facilities and simulated facilities per district, with population and its anchoring"
          columns={[
            { header: 'District' },
            { header: 'State' },
            { header: 'Facilities', numeric: true },
            { header: 'With history', numeric: true },
            { header: 'Population', numeric: true },
            { header: 'Anchoring' },
          ]}
          rows={summary.byDistrict.map((district) => [
            district.name,
            district.stateName,
            formatCount(district.facilities),
            formatCount(district.simulatedFacilities),
            formatCount(district.population),
            <Badge
              key="anchored"
              className={
                district.anchored ? SOURCE_STATUS_TONES.retrieved : SOURCE_STATUS_TONES.partial
              }
            >
              {district.anchored ? 'census' : 'assumed'}
            </Badge>,
          ])}
        />
      </Panel>

      <Panel
        id="observations"
        title="What the network heard, against what happened"
        description={
          <>
            The left column is what reached the platform. The right column is what actually happened
            — and none of it is observable, because a facility that ran out dispensed nothing, and
            nothing is exactly what its ledger recorded. Keeping the two apart is the reason the
            platform treats a shortage it cannot see as a modelling problem rather than an absence
            of news.
          </>
        }
      >
        <div className="grid gap-3 lg:grid-cols-2">
          <CountList
            id="observations-heard"
            title="Observations the network received"
            counts={summary.observations}
            footnote="Each of these records carries synthetic: true and a simulated provenance."
          />
          <CountList
            id="observations-truth"
            title="Ground truth the platform cannot observe"
            counts={summary.groundTruth}
            footnote="Generated for evaluation and for tests. No page in the platform reports these as measured."
          />
        </div>
      </Panel>

      <Panel
        id="reporting"
        title="Reporting and ordering"
        description={
          <>
            A facility that has gone quiet has unknown stock, not empty shelves. Reporting gaps are
            detected with the same rule the platform uses, so these are the gaps an officer would
            actually see rather than a second opinion.
          </>
        }
      >
        <div className="grid gap-3 sm:grid-cols-3 lg:grid-cols-6">
          <StatCard
            label="Facilities reporting"
            value={formatCount(summary.reporting.facilitiesReporting)}
          />
          <StatCard label="With a gap" value={formatCount(summary.reporting.facilitiesWithGaps)} />
          <StatCard label="Gaps" value={formatCount(summary.reporting.gaps)} />
          <StatCard label="Longest gap" value={`${String(summary.reporting.longestGapDays)} d`} />
          <StatCard label="Offline spans" value={formatCount(summary.reporting.offlineSpans)} />
          <StatCard
            label="Orders placed"
            value={formatCount(summary.ordering.ordersPlaced)}
            hint={`${formatCount(summary.ordering.ordersStillInFlight)} still in flight`}
          />
        </div>
      </Panel>

      <footer className="flex flex-wrap items-center gap-x-4 gap-y-1 border-t border-ink-700 pt-6 text-sm text-fg-subtle">
        <Link className="text-accent underline-offset-4 hover:underline" href="/">
          Back to the overview
        </Link>
        <span>
          Generated from seed <code className="font-mono">{DEMO_SEED}</code> · anchors retrieved{' '}
          {RETRIEVAL_DATE}
        </span>
        <span>Licensed under Apache-2.0</span>
      </footer>
    </div>
  );
}
