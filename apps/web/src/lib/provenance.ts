/**
 * What on these surfaces is real, and what is generated.
 *
 * The demo's most dangerous reading is not a wrong figure, it is a right figure
 * taken for a real one. So the platform answers the question once, in one place,
 * and every command surface can point at it: which layers were **retrieved from
 * published sources**, which are **simulated from those anchors plus documented
 * assumptions**, and under which seed.
 *
 * The lists are deliberately short and concrete rather than reassuring. "All
 * data is simulated" is true and useless; a judge, or a ministry officer, needs
 * to know that the district populations and the medicine list are real published
 * values while the stock, the consumption and the outbreaks are generated — and
 * that every generated record carries `synthetic: true` so a surface that showed
 * one as a measurement would be caught by the test suite.
 *
 * The assumptions themselves are not restated here. They live, with their
 * sources, licences and retrieval dates, in `docs/DATA_PROVENANCE.md`, and this
 * file names that document rather than paraphrasing it — a second copy of a real
 * table is a second table that can drift.
 */

/** Where the full table lives, named on every surface that shows a figure. */
export const PROVENANCE_DOCUMENT = 'docs/DATA_PROVENANCE.md';

export interface ProvenanceLayer {
  readonly layer: string;
  readonly detail: string;
  /** Where the values came from, for a reader who wants to check them. */
  readonly source: string;
}

