export interface ProvenanceView {
  readonly seed: string;
  readonly fingerprint: string;
  readonly scenarioId: string;
  readonly scenarioLabel: string;
  readonly window: { readonly from: string; readonly to: string; readonly days: number };
  readonly document: string;
  readonly realLayers: readonly ProvenanceLayer[];
  readonly simulatedLayers: readonly ProvenanceLayer[];
}

/** The panel's content, from the store's own facts rather than a constant here. */
export function provenanceFor(info: {
  readonly seed: string;
  readonly fingerprint: string;
  readonly scenarioId: string;
  readonly scenarioLabel: string;
  readonly window: { readonly from: string; readonly to: string; readonly days: number };
}): ProvenanceView {
  return {
    seed: info.seed,
    fingerprint: info.fingerprint,
    scenarioId: info.scenarioId,
    scenarioLabel: info.scenarioLabel,
    window: info.window,
    document: PROVENANCE_DOCUMENT,
    realLayers: REAL_LAYERS,
    simulatedLayers: SIMULATED_LAYERS,
  };
}
