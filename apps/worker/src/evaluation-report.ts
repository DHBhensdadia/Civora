import type { BacktestReport, CensoringPair, MethodScore } from '@civora/forecasting';

import type { PolicyComparison } from './policy';

/**
 * The backtest report, written by the command that ran the backtest.
 *
 * Generated rather than hand-written so the numbers in `docs/EVALUATION.md`
 * cannot drift from the code that produced them, and so a reader can reproduce
 * the whole document by running one command with a published seed.
 *
 * The limitations section is not decoration. A report that published the
 * favourable numbers and left the approximations to be discovered would be worse
 * than no report, because it would be trusted.
 */

export interface ReportContext {
  /** The command a reader would type to reproduce this document. */
  readonly command: string;
  readonly generatedOn: string;
  readonly seed: string;
  readonly profile: string;
  readonly scenario: string;
  readonly dataset: {
    readonly pairs: number;
    readonly unmetDays: number;
    readonly unitsWanted: number;
    readonly unitsDispensed: number;
  };
  /** Whether the Cloud backend ran, and why not if it did not. */
  readonly cloudBackend: string;
  /** The forecast-on against forecast-off replay over the same days. */
  readonly policy: PolicyComparison;
}

const number = (value: number): string => value.toLocaleString('en-IN');

const rate = (value: number): string => value.toFixed(3);

const percent = (value: number): string => `${(value * 100).toFixed(1)}%`;

const share = (part: number, whole: number): string =>
  whole === 0 ? 'n/a' : percent(part / whole);

const methodLabel = (method: MethodScore['method']): string =>
  method === 'engine' ? '**engine (chosen per series)**' : `\`${method}\``;

const scoreRow = (score: MethodScore): string =>
  `| ${methodLabel(score.method)} | ${rate(score.pinball50)} | ${rate(score.pinball90)} | ${rate(
    score.meanAbsoluteError,
  )} | ${percent(score.meanRelativeError)} | ${rate(score.mase)} | ${percent(
    score.coverage90,
  )} | ${percent(score.recordedCoverage90)} |`;

const censoringRow = (pair: CensoringPair): string =>
  `| ${number(pair.forecastDays)} | ${rate(pair.actualMean)} | ${rate(
    pair.correctedMean,
  )} | ${rate(pair.corrected.meanAbsoluteError)} | ${percent(
    pair.corrected.meanRelativeError,
  )} | ${rate(pair.corrected.recordedMeanAbsoluteError)} | ${rate(pair.uncorrectedMean)} | ${rate(
    pair.uncorrected.meanAbsoluteError,
  )} | ${percent(pair.uncorrected.meanRelativeError)} | ${rate(
    pair.uncorrected.recordedMeanAbsoluteError,
  )} |`;

const improvementOn = (pair: CensoringPair): string => {
  if (pair.forecastDays === 0) {
    return 'n/a — no origins of this kind were found, so the correction was not exercised';
  }
  if (pair.uncorrected.meanAbsoluteError === 0) {
    return 'n/a';
  }
  const change = 1 - pair.corrected.meanAbsoluteError / pair.uncorrected.meanAbsoluteError;
  return `${change >= 0 ? 'a reduction of ' : 'an increase of '}${percent(Math.abs(change))}`;
};

export function renderEvaluationReport(report: BacktestReport, context: ReportContext): string {
  const worstBaseline = report.scores
    .filter((score) => score.method !== 'engine')
    .reduce<MethodScore | null>(
      (worst, score) =>
        worst === null || score.meanRelativeError > worst.meanRelativeError ? score : worst,
      null,
    );

  const bestBaseline = report.scores.find((score) => score.method !== 'engine') ?? null;
  const engine = report.scores.find((score) => score.method === 'engine') ?? null;
  const beats = engine !== null && bestBaseline !== null && engine.mase < bestBaseline.mase;

  return `# Evaluation — Poorvadarshan demand forecasting

> Generated by \`${context.command}\` on ${context.generatedOn}.
> Do not edit by hand: re-run the command. Everything below is measured, and the
> approximations it rests on are stated rather than implied.

| | |
|---|---|
| Seed | \`${context.seed}\` |
| Profile | ${context.profile} — scenario \`${context.scenario}\` |
| Series scored | ${number(report.series)} facility-item pairs |
| Origins | ${number(report.origins)} forecast origins, ${number(report.horizonDays)}-day horizon |
| Scored days | ${number(report.scoredDays)} forecast days across ${number(
    report.series,
  )} series spanning ${report.from} → ${report.to} |
| Demand in the dataset | ${number(context.dataset.unitsWanted)} units wanted, ${number(
    context.dataset.unitsDispensed,
  )} dispensed, over ${number(context.dataset.unmetDays)} facility-item-days on which demand went unmet |
| Runtime | ${number(report.elapsedMs)} ms |
| Cloud backend (\`bqml\`) | ${context.cloudBackend} |

## 1. Censored demand, and what the correction is worth

The engine is run twice over the same origins, the same histories and the same
days, choosing the same method each time. The only difference is whether the days
on which the shelf was empty were replaced with an estimate of what was wanted
rather than left at zero.

Three populations are reported, because the aggregate one is close to useless and
saying so is part of the measurement:

- **Every origin.** The correction can only move a forecast whose history contains
  a stock-out, so on a dataset where most series never ran dry this row is mostly a
  record of series the correction never touched. It is published so the other two
  rows cannot be read as the whole story.
- **Origins with a censored history.** The population the correction acts on.
- **Origins whose horizon contains a day demand went unmet.** The population it is
  *aimed* at — a forecast made into or across a shortage. This is the number an
  officer would act on, so it is stated as the headline.

Scored against **latent** demand — what was wanted, which only the generated world
knows:

| Population | Scored days | Actual mean | Corrected mean | Corrected MAE | Corrected rel. | Corrected vs recorded | Uncorrected mean | Uncorrected MAE | Uncorrected rel. | Uncorrected vs recorded |
|---|---|---|---|---|---|---|---|---|---|---|
| **Origins whose horizon contains unmet demand** ${censoringRow(report.censoring.horizon)}
| Origins with a stock-out in the history ${censoringRow(report.censoring.affected)}
| Every origin ${censoringRow(report.censoring.all)}

${number(report.censoring.censoredDays)} censored days were found across the scored
histories, affecting ${number(report.censoring.affectedOrigins)} of ${number(
    report.origins,
  )} origins; ${number(report.censoring.horizonOrigins)} origins had a day inside
their horizon on which demand went unmet.

On the population with a censored history, correcting censored days changed the error
against latent demand by **${improvementOn(report.censoring.affected)}**; on the
population with unmet demand ahead, by **${improvementOn(report.censoring.horizon)}**.
The two differ because they are different populations on purpose: a stock-out a
hundred days back does not change today's forecast, and a shortage arriving tomorrow
need not have a censored day behind it — stock also runs out when a delivery fails,
with no unusual demand behind it at all.

Three readings of the same table are worth stating rather than leaving to be found:

- Against **recorded** issues the corrected engine looks *worse*. It is predicting
  demand the facility could not meet, and the ledger has no record of the patients
  who went elsewhere. That is the trade this project makes deliberately, and it is
  the reason the two columns sit side by side.
- The correction moves the mean prediction *closer* to what was actually wanted.
  On the affected population the uncorrected engine reads ${share(
    report.censoring.affected.uncorrectedMean,
    report.censoring.affected.actualMean,
  )} of latent demand and the corrected engine reads ${share(
    report.censoring.affected.correctedMean,
    report.censoring.affected.actualMean,
  )}.
- Where the corrected engine is *not* better on the headline row, the number above
  is negative and stays negative here. The correction is a deliberate bias upwards
  on censored days; on a horizon whose shortage is driven by a failed delivery
  rather than by demand, that bias buys nothing and costs error.

## 2. Every mandated baseline, on the same days

Pinball loss is the proper score for a quantile forecast — lower is better. MASE is
the error divided by the seasonal-naive benchmark's error over the identical days, so
1.000 means "no better than repeating last week". Relative error is reported because
the absolute figure is dominated by whichever item moves in the largest numbers.

| Method | Pinball (p50) | Pinball (p90) | MAE (latent) | Rel. error | MASE | p90 coverage (latent) | p90 coverage (recorded) |
|---|---|---|---|---|---|---|---|
${report.scores.map(scoreRow).join('\n')}

Nominal coverage for the upper bound is 0.900. Achieved against *recorded* issues:
**${percent(engine?.recordedCoverage90 ?? 0)}**; against latent demand:
**${percent(engine?.coverage90 ?? 0)}**.

${
  beats
    ? `The engine's own choice is ahead of the best of the mandated baselines (MASE ${rate(
        engine.mase,
      )} against ${rate(bestBaseline.mase)}).`
    : `**A mandated baseline matches or beats the engine's own choice** (MASE ${rate(
        engine?.mase ?? 0,
      )} for the engine against ${rate(bestBaseline?.mase ?? 0)} for \`${
        bestBaseline?.method ?? 'none'
      }\`). That is published here rather than tuned away: where a simple method wins, the
      engine should be selecting it.`
}${
    worstBaseline === null
      ? ''
      : ` The weakest baseline over the population is ${methodLabel(
          worstBaseline.method,
        )} at MASE ${rate(worstBaseline.mase)}.`
  }

## 3. Would the platform have warned in time?

The upper bound is compared with the shelf at each origin. A *shortage* is a period
inside the horizon on which demand actually went unmet, which the generated world
records and the platform never sees.

| | |
|---|---|
| Origins scored | ${number(report.warning.originsScored)} |
| Shortages inside the horizon | ${number(report.warning.shortages)} |
| Flagged in advance | ${number(report.warning.warned)} (${share(
    report.warning.warned,
    report.warning.shortages,
  )}) |
| Missed | ${number(report.warning.missed)} |
| Warnings with no shortage after them | ${number(report.warning.falseAlarms)} |
| Mean advance on a shortfall | ${report.warning.meanAdvanceDays.toFixed(1)} days |

## 4. What the forecast would have done to the shelves

This is a **replay**, not a second run of the generator, and the difference matters.
The world's own ordering rule computes what to order from the issues it recorded —
including, during a stock-out, the issues it could not record. Both arms are run over
the same days, the same lead times and the same demand, and the only thing that
changes is the quantity on each order: the platform's arm sizes it from its own
forecast of the history available that day, at the upper quantile over the lead time,
which is where the censored-demand correction enters. Never below what the world
itself ordered, so the comparison isolates the forecast rather than modelling a
lazier reviewer than the one that actually placed the order.

The target is **latent** demand, because the question is whether people got the
medicine rather than whether the ledger balanced.

| | Forecast off (the world's own quantities) | Forecast on |
|---|---|---|
| Pair-days on which somebody wanted something and got none of it | ${number(
    context.policy.baseline.unsuppliedDays,
  )} (${percent(context.policy.baseline.unsuppliedDayRate)}) | ${number(
    context.policy.platform.unsuppliedDays,
  )} (${percent(context.policy.platform.unsuppliedDayRate)}) |
| Short days per thousand pair-days | ${rate(
    context.policy.baseline.shortageRatePerThousandDays,
  )} | ${rate(context.policy.platform.shortageRatePerThousandDays)} |
| Fill rate — units dispensed ÷ units wanted | ${rate(context.policy.baseline.fillRate)} | ${rate(
    context.policy.platform.fillRate,
  )} |
| Units dispensed of ${number(context.policy.platform.demandedUnits)} wanted | ${number(
    context.policy.baseline.dispensedUnits,
  )} | ${number(context.policy.platform.dispensedUnits)} |
| Units that went unmet | ${number(context.policy.baseline.unmetUnits)} | ${number(
    context.policy.platform.unmetUnits,
  )} |
| Orders the forecast could judge (14 days of history behind them) | — | ${number(
    context.policy.ordersJudged,
  )} of ${number(context.policy.ordersTotal)} |
| Orders resized away from the world's own quantity | 0 | ${number(context.policy.ordersResized)} |

Replayed over ${number(context.policy.pairs)} of ${number(
    context.policy.pairsAvailable,
  )} facility-item pairs (${number(context.policy.pairDays)} pair-days, mean lead time ${context.policy.meanLeadTimeDays.toFixed(
    1,
  )} days), taking ${number(context.policy.elapsedMs)} ms.

**Replay fidelity ${context.policy.fidelity.toFixed(
    3,
  )}** — driven by the world's own order quantities, the replay reproduces the
world's own short days to this share. A counterfactual built on a replay that cannot
reproduce the outcome it was built from measures the replay, not the policy, so this
figure is stated before the comparison above is read.

On this dataset the two arms are close, and that is stated rather than tuned away.
The generator's own ordering rule already keeps these shelves at a ${rate(
    context.policy.baseline.fillRate,
  )} fill rate, so there is very little for a forecast to recover — a shortage has to
happen before predicting one can help — and the platform's arm is floored at the
quantity the facility itself ordered, so a forecast that would have ordered *less* is
not credited here. What this replay measures is the medicine the platform would have
put on the shelf that the facility's own rule would not have; on a world where nearly
everybody was served, that number is small, and a reader should treat the two fill
rates above as the honest answer rather than as a result that needs polishing. A
comparison that credited the stock a better forecast avoids holding would need a cost
model this project has not built, and it is not implied by anything above.

## 5. What this report does not establish

1. **The Cloud backend has not been executed.** ${context.cloudBackend}. The \`bqml\`
   adapter is unit-tested against fixtures and its live path is unverified. No number
   above comes from BigQuery.
2. **Latent demand inside a stock-out spell is spread evenly across its days.** The
   generator records a spell's total unmet units and its length, not its daily shape.
   The totals are exact; the within-spell distribution is an assumption, and it is the
   assumption the scored target and the replay both rest on.
3. **The replay is a counterfactual with three stated exclusions.** Expiry and cold-chain
   losses are ignored — one undated pool of stock, in both arms equally, so the comparison
   is unaffected but the absolute rates are optimistic in both. Stock is not moved between
   facilities; that is a later phase, and a replay that quietly redistributed would be
   measuring it. And demand is latent rather than recorded, so the fill rates here are not
   the ones the ledger would show.
4. **The replay measures shortages avoided, not stock saved.** Both arms are floored at the
   quantity the world itself ordered, which isolates the forecast but also means a
   recommendation to order less is scored as no change. On a well-supplied dataset that
   makes the platform's arm look almost inert, and the report says so above rather than
   reporting only the arm it prefers.
4. **One seed and one profile.** These figures are the demonstration dataset under
   \`${context.seed}\`. The national profile has not been backtested.
5. **Nothing here is a claim about a real facility.** Every series is generated. The
   numbers measure whether the engine works, not how any real supply chain behaves.

## 6. Reproducing this document

\`\`\`bash
${context.command}
\`\`\`

The command regenerates this file from the same seed. If the figures differ, the engine
changed — which is what the version stamp on every forecast is for.
`;
}
