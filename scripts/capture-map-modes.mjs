#!/usr/bin/env node

/**
 * Screenshot the control tower in both map modes, and say what each one showed.
 *
 * Phase 8's evidence list asks for the geographic view with **no Maps key** and
 * the **keyed** path, screenshotted and recorded, because a fallback nobody has
 * looked at is a fallback that is broken. The repository ships no key, so the
 * keyed run uses a placeholder: it exercises the port's decision, not Google's
 * servers, and the record says so rather than implying a live map was rendered.
 *
 * Usage: node scripts/capture-map-modes.mjs <output-directory>
 *
 * The two runs are separate server processes on separate ports, started from the
 * production build (`pnpm build` first). Output is PNGs plus `map-modes.md`, the
 * written record this evidence is supposed to leave behind.
 */

import { spawn } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { chromium } from '@playwright/test';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const serverEntry = join(repoRoot, 'scripts', 'serve-standalone.mjs');
const outDir = resolve(process.argv[2] ?? join(repoRoot, 'map-modes'));
mkdirSync(outDir, { recursive: true });

/** A key that is a real string and not a real credential. */
const PLACEHOLDER_KEY = 'civora-placeholder-key-not-a-credential';

const MODES = [
  { name: 'no-key', key: undefined, expected: 'schematic', port: 3213 },
  { name: 'keyed', key: PLACEHOLDER_KEY, expected: 'google-maps', port: 3214 },
];

const waitForServer = async (url, deadlineMs) => {
  const until = Date.now() + deadlineMs;
  for (;;) {
    try {
      const response = await fetch(url);
      if (response.ok) {
        return;
      }
    } catch {
      // Not up yet; the loop is the retry.
    }
    if (Date.now() > until) {
      throw new Error(`the server at ${url} did not answer within ${String(deadlineMs)} ms`);
    }
    await new Promise((done) => setTimeout(done, 250));
  }
};

const results = [];

for (const mode of MODES) {
  const env = {
    ...process.env,
    PORT: String(mode.port),
    HOSTNAME: '127.0.0.1',
    CIVORA_DATA_PROVIDER: 'in-memory',
    CIVORA_AUTH_PROVIDER: 'fixture',
    CIVORA_REASONING_PROVIDER: 'fixture',
  };
  if (mode.key === undefined) {
    delete env.NEXT_PUBLIC_GOOGLE_MAPS_API_KEY;
  } else {
    env.NEXT_PUBLIC_GOOGLE_MAPS_API_KEY = mode.key;
  }

  const server = spawn(process.execPath, [serverEntry], { env, stdio: 'inherit' });
  try {
    const base = `http://127.0.0.1:${String(mode.port)}`;
    await waitForServer(`${base}/healthz`, 60_000);

    const browser = await chromium.launch();
    try {
      const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
      await page.goto(`${base}/command`, { waitUntil: 'domcontentloaded' });
      await page.getByTestId('map-renderer').waitFor({ timeout: 60_000 });

      const renderer = (await page.getByTestId('map-renderer').textContent())?.trim() ?? '';
      const refusal = (await page.getByTestId('map-refusal').textContent())?.trim() ?? '';
      const markers = await page.locator('[data-testid^="map-marker-"]').count();

      const panel = page.getByRole('region', { name: 'Where the risk is' });
      const image = `${mode.name}.png`;
      await panel.first().screenshot({ path: join(outDir, image) });

      if (!renderer.includes(mode.expected)) {
        throw new Error(
          `the ${mode.name} run rendered "${renderer}" and the port should have chosen ${mode.expected}`,
        );
      }
      results.push({ ...mode, renderer, refusal, markers, image });
    } finally {
      await browser.close();
    }
  } finally {
    server.kill('SIGTERM');
    // A killed server releases the port asynchronously; the next mode has its
    // own port, so the wait is only about not leaving two processes behind.
    await new Promise((done) => setTimeout(done, 500));
  }
}

const record = [
  '# The control tower in both map modes',
  '',
  'Generated by `node scripts/capture-map-modes.mjs <directory>`; the PNGs sit beside',
  'this file. The keyed run uses a placeholder key, so it exercises the port’s',
  'decision rather than Google’s servers.',
  '',
  '| Mode | Renderer reported | Region markers | What the surface said | Screenshot |',
  '| --- | --- | --- | --- | --- |',
  ...results.map(
    (result) =>
      `| ${result.name} | \`${result.renderer}\` | ${String(result.markers)} | ${result.refusal.replaceAll('|', '\\|')} | \`${result.image}\` |`,
  ),
  '',
  'Both modes draw the same regions, the same values and the same classes from the',
  'platform’s own coordinates: with no key the port selects the schematic renderer,',
  'and with a key it selects Google Maps and the surface says the schematic view',
  'below is drawn from the same markers. Nothing in either mode requests anything',
  'off the machine — asserted in `e2e/map-fallback.spec.ts`.',
  '',
].join('\n');

writeFileSync(join(outDir, 'map-modes.md'), record);
console.log(`wrote ${join(outDir, 'map-modes.md')}`);
